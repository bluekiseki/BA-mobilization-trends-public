// "1st anniversary", "1.5 anniversary", and the localized equivalents
export function anniversaryLabel(years: number, lang: StoryLang): string {
  if (lang === 'ko') return `${years}주년`;
  if (lang === 'ja') return `${years}周年`;
  if (lang === 'zh-Hant') return `${years}週年`;
  const rest = years % 100;
  const suffix = !Number.isInteger(years) ? '' : rest >= 11 && rest <= 13 ? 'th' : (({ 1: 'st', 2: 'nd', 3: 'rd' } as Record<number, string | undefined>)[years % 10] ?? 'th');
  return `${years}${suffix} anniversary`;
}
